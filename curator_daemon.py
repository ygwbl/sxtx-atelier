            msg["echo"] = {
                "author": "工坊回笔 · Sxtx",
                "content": echo_text,
                "time": datetime.now(timezone.utc).isoformat()
            }
            changed = True
            log(f"★ 已完成对访客【{author}】的回笔。")
            
